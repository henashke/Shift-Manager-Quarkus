-- OAuth 2.1 for the MCP server: chat apps (Claude, ChatGPT, Gemini...) register themselves as clients, users approve
-- them once, and the app then holds a refresh token. Secrets, codes and tokens are stored hashed (SHA-256 hex).

-- Registered by the apps themselves (dynamic client registration). Public clients (PKCE only) have no secret.
CREATE TABLE oauth_clients
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    client_id          VARCHAR(64)                             NOT NULL,
    client_secret_hash VARCHAR(64),
    client_name        VARCHAR(200),
    -- One redirect URI per line
    redirect_uris      TEXT                                    NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_oauth_clients PRIMARY KEY (id),
    CONSTRAINT uq_oauth_clients_client_id UNIQUE (client_id)
);

-- Short-lived, single-use authorization codes, bound to the PKCE challenge and redirect URI they were issued for
CREATE TABLE oauth_authorization_codes
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code_hash      VARCHAR(64)                             NOT NULL,
    client_id      BIGINT                                  NOT NULL,
    user_id        BIGINT                                  NOT NULL,
    redirect_uri   TEXT                                    NOT NULL,
    code_challenge VARCHAR(128)                            NOT NULL,
    expires_at     TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_oauth_authorization_codes PRIMARY KEY (id),
    CONSTRAINT uq_oauth_authorization_codes_code_hash UNIQUE (code_hash),
    CONSTRAINT fk_oauth_authorization_codes_client FOREIGN KEY (client_id) REFERENCES oauth_clients (id) ON DELETE CASCADE,
    CONSTRAINT fk_oauth_authorization_codes_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- Refresh tokens issued to an OAuth client (null: the web app's own sessions). They only work for that client.
ALTER TABLE refresh_tokens
    ADD COLUMN oauth_client_id BIGINT;
ALTER TABLE refresh_tokens
    ADD CONSTRAINT fk_refresh_tokens_oauth_client FOREIGN KEY (oauth_client_id) REFERENCES oauth_clients (id) ON DELETE CASCADE;
